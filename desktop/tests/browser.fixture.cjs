const { app, BrowserWindow } = require('electron');
const { createServer } = require('node:http');
const assert = require('node:assert/strict');
const path = require('node:path');
const { BrowserHost } = require('../electron/browser.cjs');
app.setPath('userData', process.env.COWORK_BROWSER_TEST_DATA);
let host, window, server;
const deadline = setTimeout(() => { console.error('browser fixture timeout'); app.exit(1); }, 30000);
app.whenReady().then(async () => {
  server = createServer((_request, response) => { response.setHeader('Content-Type', 'text/html; charset=utf-8'); response.end('<html><head><title>网页回归夹具</title></head><body><label>任务名称<input id="name"></label><button id="submit" onclick="document.getElementById(\'result\').textContent=document.getElementById(\'name\').value">保存</button><p id="result"></p></body></html>'); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  let allowed = true, result, requestId = 0;
  const tab = { id: 'fixture', kind: 'web', url, owner: 'agent' };
  const backend = { call: async (method, params) => {
    if (method === 'browser.host_check') { if (!allowed) throw new Error('cancelled fixture'); return { ok: true }; }
    if (method === 'browser.host_result') { result = params.result; return { ok: true }; }
    if (method === 'browser.host_state') return { ok: true };
    if (method === 'workbench.list') return { tabs: [tab] };
    throw new Error(method);
  } };
  window = new BrowserWindow({ show: false, width: 1100, height: 850, webPreferences: { sandbox: true } });
  host = new BrowserHost({ root: path.resolve(__dirname, '../..'), backend, getWindow: () => window });
  async function run(action, args = {}) { result = undefined; await host.handle({ id: String(++requestId), conversation_id: 'test', tab, action, arguments: args }); return result; }
  assert.equal((await run('open')).ok, true);
  const item = host.views.get(tab.id);
  if (!item.ready) await new Promise(resolve => item.view.webContents.once('did-finish-load', resolve));
  let observed = await run('observe');
  assert.equal(observed.ok, true, JSON.stringify(observed));
  assert.match(JSON.stringify(observed), /任务名称/);
  const input = observed.elements.find(element => element.tag === 'input');
  assert.ok(input, JSON.stringify(observed.elements));
  const filled = await run('browser_action', { action: 'fill', element_id: input.id, page_version: observed.page_version, text: '保存后的内容' });
  assert.equal(filled.ok, true, JSON.stringify(filled));
  const stale = await run('browser_action', { action: 'fill', element_id: input.id, page_version: observed.page_version, text: '不能重复' });
  assert.equal(stale.ok, false);
  observed = await run('observe');
  const button = observed.elements.find(element => element.tag === 'button');
  const clicked = await run('browser_action', { action: 'click', element_id: button.id, page_version: observed.page_version });
  assert.equal(clicked.ok, true, JSON.stringify(clicked));
  await new Promise(resolve => setTimeout(resolve, 300));
  assert.equal(await host.js(item, 'document.getElementById("result").textContent'), '保存后的内容');
  allowed = false;
  const cancelled = await run('navigate', { url: 'http://127.0.0.1:1' });
  assert.equal(cancelled.ok, false);
  assert.equal(item.view.webContents.getURL(), url + '/');
  allowed = true;
  tab.owner = 'human';
  const shown = await host.show({ conversation_id: 'test', tab_id: tab.id, bounds: { x: 0, y: 0, width: 800, height: 600 } });
  assert.equal(shown.owner, 'human');
  assert.equal((await run('command', {command:'zoom', value:1.2})).zoom, 1.2);
  assert.equal((await run('command', {command:'zoom', value:0})).ok, false);
  assert.equal((await run('command', {command:'zoom', value:1})).zoom, 1);
  const match = new Promise(resolve => item.view.webContents.once('found-in-page', (_event,result) => resolve(result)));
  assert.equal((await run('command', {command:'find',text:'任务名称'})).ok, true);
  assert.ok((await match).matches > 0);
  await run('command', {command:'stop_find'});
  tab.owner = 'available';
  await host.show({ conversation_id: 'test', tab_id: tab.id, bounds: { x: 0, y: 0, width: 800, height: 600 } });
  assert.equal(window.contentView.children.at(-1), host.inputShield);
  assert.equal(item.view.getVisible(), true);
  assert.equal(host.inputShield.getVisible(), true);
  observed = await run('observe');
  const handoffInput = observed.elements.find(element => element.tag === 'input');
  assert.equal((await run('browser_action', { action: 'fill', element_id: handoffInput.id, page_version: observed.page_version, text: '交还后的内容' })).ok, true);
  observed = await run('observe');
  const handoffButton = observed.elements.find(element => element.tag === 'button');
  assert.equal((await run('browser_action', { action: 'click', element_id: handoffButton.id, page_version: observed.page_version })).ok, true);
  assert.equal(await host.js(item, 'document.getElementById("result").textContent'), '交还后的内容');
  tab.owner = 'human';
  await host.show({ conversation_id: 'test', tab_id: tab.id, bounds: { x: 0, y: 0, width: 800, height: 600 } });
  assert.equal(host.inputShield.getVisible(), false);
  await host.show({ tab_id: '' });
  assert.equal(host.visible, null);
  assert.equal(window.contentView.children.includes(item.view), false);
  assert.equal(host.backgroundWindow.contentView.children.includes(item.view), true);
  assert.equal(host.backgroundWindow.isVisible(), false);
  observed = await run('observe');
  assert.equal(observed.image_status, 'ready');
  assert.equal((await run('browser_action', { action: 'fill', element_id: observed.elements.find(element => element.tag === 'input').id, page_version: observed.page_version, text: '后台继续完成' })).ok, true);
  observed = await run('observe');
  assert.equal((await run('browser_action', { action: 'click', element_id: observed.elements.find(element => element.tag === 'button').id, page_version: observed.page_version })).ok, true);
  assert.equal(await host.js(item, 'document.getElementById("result").textContent'), '后台继续完成');
  assert.equal((await run('close')).ok, true);
  console.log('BROWSER_FIXTURE_OK');
}).then(() => { clearTimeout(deadline); server?.close(); window?.destroy(); app.exit(0); }).catch(error => { console.error(error); clearTimeout(deadline); server?.close(); window?.destroy(); app.exit(1); });
