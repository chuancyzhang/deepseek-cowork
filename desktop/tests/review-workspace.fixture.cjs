const {app,BrowserWindow}=require('electron');
const path=require('node:path'),assert=require('node:assert/strict'),fs=require('node:fs/promises');
const data=process.env.COWORK_REVIEW_TEST_DATA;
app.setPath('userData',path.join(data,'profile'));
app.commandLine.appendSwitch('disable-gpu');
let window;const errors=[];
const deadline=setTimeout(()=>{console.error('review workspace fixture timeout',errors);app.exit(1);},35000);
app.whenReady().then(async()=>{
  window=new BrowserWindow({show:false,width:1180,height:820,webPreferences:{offscreen:true,backgroundThrottling:false,sandbox:true,contextIsolation:true,nodeIntegration:false}});
  window.webContents.on('console-message',details=>{if(details.level==='error')errors.push(details.message);});
  const read=async code=>{try{return await window.webContents.executeJavaScript(code);}catch(error){throw Error(code+'\n'+error.message+'\n'+errors.join('\n'));}};
  const until=async(code)=>{const start=Date.now();while(Date.now()-start<6000){if(await read(code))return;await new Promise(resolve=>setTimeout(resolve,30));}throw Error('Timed out: '+code+' '+errors.join('\n'));};
  const click=async label=>{const button=`[...document.querySelectorAll('button')].find(button=>button.textContent.trim()===${JSON.stringify(label)})`;await until(`Boolean(${button})`);await read(`${button}.click()`);};
  const snap=async(name,selector='.workspace')=>{if(!process.env.COWORK_REVIEW_SCREENSHOTS)return;await new Promise(resolve=>setTimeout(resolve,150));const zoom=window.webContents.getZoomFactor();const rect=await read(`(()=>{const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:Math.round(r.x*${zoom}),y:Math.round(r.y*${zoom}),width:Math.round(r.width*${zoom}),height:Math.round(r.height*${zoom})};})()`);const image=await window.webContents.capturePage(rect);await fs.mkdir(process.env.COWORK_REVIEW_SCREENSHOTS,{recursive:true});await fs.writeFile(path.join(process.env.COWORK_REVIEW_SCREENSHOTS,name+'.png'),image.toPNG());};
  await window.loadFile(path.join(data,'dist/index.html'));
  await until('Boolean(document.querySelector(".workspace-start"))');
  assert.equal(await read('document.querySelectorAll(".workspace-tab").length'),1);
  await snap('workspace-new');
  await read('document.querySelector("[aria-label=添加上下文]").click()');
  await until('Boolean(document.querySelector(".composer-menu"))');
  assert.ok(await read('document.querySelector(".composer-menu").getBoundingClientRect().height')<350);
  await click('技能');await until('Boolean(document.querySelector(".context-description"))');
  await click('展开说明');
  assert.equal(await read('document.querySelector(".context-option .picker-row").getAttribute("aria-pressed")'),'false');
  await click('资料核对');await until('Boolean(document.querySelector(".skill-chip"))');
  const navTop=await read('document.querySelector(".composer-menu-nav").getBoundingClientRect().top');
  await click('连接器');await until('document.querySelector(".context-option .picker-row")?.textContent.includes("文档服务")');
  assert.equal(await read('document.querySelector(".composer-menu-nav").getBoundingClientRect().top'),navTop);
  await click('专家');await until('document.querySelectorAll(".context-option").length===2');
  assert.equal(await read('document.querySelectorAll(".context-check.single").length'),2);
  await click('技能');await until('document.querySelector(".submenu-heading")?.textContent.includes("技能") && document.querySelector(".context-option .picker-row")?.textContent.includes("资料核对")');
  await click('收起说明');
  await until('document.querySelector(".context-description p") && document.querySelector(".context-description p").getBoundingClientRect().height < 45');
  await snap('context-picker','.composer-menu');
  await click('浏览资料库');await until('Boolean(document.querySelector(".library-row"))');
  await read(`document.querySelector('[aria-label="添加到当前对话：访谈记录.md"]').click()`);
  await until('document.querySelector(".composer-contexts")?.textContent.includes("访谈记录.md")');
  await snap('workspace-library');
  await read('window.createReview()');await until('document.querySelectorAll(".workspace-tab").length===3');
  assert.equal(await read('Boolean(document.querySelector(".library-row"))'),true);
  await read('document.querySelector("#reopen").click()');await until('Boolean(document.querySelector(".review-paper"))');
  await snap('skill-review');
  await click('编辑内容');await until('Boolean(document.querySelector(".review-skill-editor"))');
  await read(`(()=>{const field=document.querySelectorAll('.review-skill-editor textarea')[1];Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(field,'用户保留的指导内容');field.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  await until('document.querySelector(".review-footer")?.textContent.includes("有未保存")');
  await read(`document.querySelector('[aria-label="关闭 访谈证据核对 · Skill"]').click()`);await until('Boolean(document.querySelector(".workspace-start"))');
  await read('document.querySelector("#reopen").click()');await until('document.querySelector(".review-paper")?.textContent.includes("用户保留")');
  await read('window.failSave=true');await click('保存到我的技能');await until('Boolean(document.querySelector(".review-workspace [role=alert]"))');
  assert.match(await read('document.querySelector(".review-paper").textContent'),/用户保留/);
  await click('保存到我的技能');await until('document.querySelector(".review-heading")?.textContent.includes("已保存")');
  assert.equal(await read('document.querySelector("[aria-label=消息输入]").value'),'保留我的下一条输入');
  await read('window.createReview("office")');await until('document.querySelectorAll(".workspace-tab").length===4');
  await read(`document.querySelector('[role=tab][title="访谈分析报告.docx"]').click()`);await until('Boolean(document.querySelector(".review-formats"))');
  await click('PPT');await snap('office-setup');
  await click('生成办公稿草稿');await until('document.querySelector(".review-workspace [role=alert]")?.textContent.includes("配置模型")');
  assert.equal(await read('document.querySelector(".review-formats .selected").textContent'),'PPT');
  await read('document.querySelector("#switch").click()');await until('document.querySelectorAll(".workspace-tab").length===1');
  assert.equal(await read('Boolean(document.querySelector(".review-workspace"))'),false);
  await read('window.delayGet=true;document.querySelector("#switch").click()');await until('Boolean(window.releaseGet)');
  await read('document.querySelector("#switch").click()');await until('document.querySelectorAll(".workspace-tab").length===1');
  await read('window.delayGet=false;window.releaseGet()');
  assert.equal(await read('Boolean(document.querySelector(".review-workspace"))'),false);
  await read('document.querySelector("#switch").click()');await until('Boolean(document.querySelector(".review-formats"))');
  window.setSize(800,650);window.webContents.setZoomFactor(1.25);
  await read('document.querySelector("#theme").click()');
  await until('Boolean(document.querySelector(".dark"))');
  assert.ok(await read('document.querySelector(".review-footer button").getBoundingClientRect().bottom<=innerHeight'));
  assert.ok(await read('document.querySelector(".review-workspace").scrollWidth<=document.querySelector(".review-workspace").clientWidth+1'));
  await snap('review-narrow-dark');
  window.setSize(1180,820);window.webContents.setZoomFactor(1);
  await read("document.documentElement.dataset.theme='light';window.taskPreview({waiting:true})");
  await until('document.querySelector(".generation-task-stage")?.textContent.includes("等待开始")');
  await read('window.taskPreview({})');
  await until('document.querySelector(".generation-task strong")?.textContent.includes("正在生成办公稿")');
  assert.equal(await read('document.querySelectorAll(".generation-task").length'),1);
  assert.equal(await read('Boolean(document.querySelector(".process-timeline"))'),false);
  assert.match(await read('document.querySelector(".markdown").textContent'),/已整理的内容始终保留/);
  await snap('chat-office-generating','.task-fixture');
  await snap('chat-generation-status','.generation-task');
  await read('document.querySelector(".generation-task .process-summary").focus()');
  assert.equal(await read('document.activeElement === document.querySelector(".generation-task .process-summary")'),true);
  await read('document.activeElement.click()');
  await until('Boolean(document.querySelector(".process-timeline"))');
  await read('window.taskPreview({kind:"skill",title:"工程经验整理",ready:true})');
  await until('document.querySelector(".generation-task-stage")?.textContent.includes("草稿已提交")');
  assert.match(await read('document.querySelector(".generation-task strong").textContent'),/沉淀为 Skill/);
  await read('window.taskPreview({kind:"skill",title:"工程经验整理",status:"completed"})');
  await until('!document.querySelector(".generation-task") && !document.querySelector(".process-timeline")');
  assert.match(await read('document.querySelector(".process-summary").textContent'),/执行过程/);
  assert.equal(await read('document.querySelectorAll(".message-file-table").length'),1);
  await snap('chat-generation-completed','.task-fixture');
  await read('window.taskPreview({status:"stopping"})');
  await until('document.querySelector(".generation-task-stage")?.textContent.includes("正在停止")');
  await read('window.taskPreview({status:"interrupted"})');
  await until('!document.querySelector(".generation-task")');
  assert.match(await read('document.querySelector(".process-summary").textContent'),/已停止/);
  await read('window.taskPreview({cid:"b"})');
  await until('!document.querySelector(".generation-task")');
  await read('window.taskPreview({kind:"skill",title:"工程经验整理"})');
  await until('document.querySelector(".generation-task strong")?.textContent.includes("沉淀为 Skill")');
  await snap('chat-skill-generating','.task-fixture');
  await read('window.taskPreview({kind:"skill",pending:true,title:"工程经验整理"})');
  await until('document.querySelector(".generation-task-stage")?.textContent.includes("等待你的回答")');
  assert.ok(await read('Boolean(document.querySelector(".process-timeline"))'));
  window.setSize(500,720);window.webContents.setZoomFactor(1.25);
  await read('document.documentElement.dataset.theme="dark";document.body.style.background="var(--bg)";document.documentElement.style.setProperty("--font-scale","1.25");window.taskPreview({kind:"skill",title:"长名称需要完整阅读和复制".repeat(10)})');
  await until('document.querySelector(".generation-task-target")?.textContent.includes("长名称")');
  assert.ok(await read('document.querySelector(".generation-task").scrollWidth<=document.querySelector(".generation-task").clientWidth+1'));
  assert.equal(await read('document.querySelector("[aria-label=保留的输入]").value'),'下一步补充要求');
  await snap('chat-generation-narrow-dark','.task-fixture');
  assert.deepEqual(errors,[]);
  console.log('REVIEW_WORKSPACE_FIXTURE_OK');
}).then(()=>{clearTimeout(deadline);window?.destroy();app.exit(0);}).catch(error=>{console.error(error);clearTimeout(deadline);window?.destroy();app.exit(1);});
