const {app,BrowserWindow}=require('electron');
const path=require('node:path'),assert=require('node:assert/strict');
const data=process.env.COWORK_TASK_TEST_DATA;
app.setPath('userData',path.join(data,'profile'));
let window;const errors=[];
const deadline=setTimeout(()=>{console.error('task workspace fixture timeout',errors);app.exit(1);},20000);
app.whenReady().then(async()=>{
  window=new BrowserWindow({show:false,width:1100,height:800,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false}});
  window.webContents.on('console-message',details=>{if(details.level==='error')errors.push(details.message);});
  const read=code=>window.webContents.executeJavaScript(code);
  const until=async(code)=>{const start=Date.now();while(Date.now()-start<6000){if(await read(code))return;await new Promise(resolve=>setTimeout(resolve,30));}throw Error('Timed out: '+code+' '+errors.join('\n'));};
  const load=()=>window.loadFile(path.join(data,'dist/index.html'));
  await load();await until('Boolean(document.querySelector(".task-empty"))');
  await read('window.deliver()');await until('Boolean(document.querySelector(".call-row .error-text"))');
  assert.equal(await read('document.querySelector(".call-row .error-text").textContent'),'no browser is currently connected');
  assert.equal(await read('document.querySelector(".tool-step .error-text").textContent'),'no browser is currently connected');
  await read('document.querySelector(".call-row").click()');await until('Boolean(document.querySelector(".call-detail"))');
  assert.match(await read('document.querySelector(".call-detail").textContent'),/bsk_command_failed/);
  await read('document.querySelectorAll(".call-detail summary button")[1].click()');await until('Boolean(window.copied)');
  assert.deepEqual(JSON.parse(await read('window.copied')).error,{code:'bsk_command_failed',message:'no browser is currently connected',exit_code:1});
  await load();await until('Boolean(document.querySelector(".call-detail"))');
  assert.equal(await read('document.querySelector(".run-error").textContent'),'no browser is currently connected');
  await read('document.querySelector("#switch").click()');await until('Boolean(document.querySelector(".task-empty"))');
  assert.equal(await read('Boolean(document.querySelector(".call-detail"))'),false);
  await read('document.querySelector("#switch").click()');await until('Boolean(document.querySelector(".call-detail"))');
  assert.match(await read('document.body.textContent'),/已保存的最终回复/);
  assert.equal(await read('document.body.textContent.includes("[object Object]")'),false);
  await read('document.querySelector("[title=返回调用记录]").click()');
  await until('document.querySelectorAll(".call-row").length===2');
  assert.match(await read('document.querySelectorAll(".call-row")[1].textContent'),/已返回/);
  assert.match(await read('document.querySelectorAll(".process-tool")[1].textContent'),/已返回/);
  await read('document.querySelectorAll(".call-row")[1].click()');
  await until('document.querySelector(".call-detail")?.textContent.includes("调用返回时的结果")');
  assert.match(await read('document.querySelector(".task-detail-heading").textContent'),/已返回/);
  assert.match(await read('document.querySelector(".call-detail").textContent'),/"status": "queued"/);
  assert.deepEqual(errors,[]);
  console.log('TASK_WORKSPACE_FIXTURE_OK');
}).then(()=>{clearTimeout(deadline);window?.destroy();app.exit(0);}).catch(error=>{console.error(error);clearTimeout(deadline);window?.destroy();app.exit(1);});
